// Picks a random-layout seed for each level that the autopilot can finish
// without falling, and writes them to src/level-seeds.js.
//   node scripts/find-seeds.mjs
import { writeFileSync } from 'node:fs';
import { generateLevel } from '../src/course.js';
import { createRun, tick } from '../src/run.js';
import { createBot, botInput } from '../src/bot.js';

const LEVEL_COUNT = 30;

export function botRun(course, maxSeconds = 240) {
  const run = createRun(course);
  const bot = createBot(run);
  const checkpoints = [];
  for (let i = 0; i < 120 * maxSeconds; i++) {
    for (const e of tick(run, botInput(bot))) {
      if (e.type === 'checkpoint') checkpoints.push(e.index);
      if (e.type === 'finish') return { finished: true, time: e.time, falls: run.falls, checkpoints };
    }
    if (run.falls > 0) break;
  }
  return { finished: false, falls: run.falls };
}

const seeds = [];
for (let i = 0; i < LEVEL_COUNT; i++) {
  let found = null;
  for (let k = 0; k < 400 && !found; k++) {
    const seed = 1000 * (i + 1) + k;
    const course = generateLevel(i, seed, LEVEL_COUNT);
    const r = botRun(course);
    if (r.finished && r.falls === 0 && r.checkpoints.join() === course.checkpoints.map((c) => c.index).join()) {
      found = { seed, time: r.time, tries: k + 1, anchors: course.anchors.length, blockers: course.boxes.filter((b) => b.kind === 'blocker').length };
    }
  }
  if (!found) throw new Error(`no finishable seed for level ${i + 1}`);
  seeds.push(found.seed);
  console.log(`level ${String(i + 1).padStart(2)}: seed ${found.seed} (try ${found.tries}), ${found.anchors} anchors, ${found.blockers} blockers, bot ${found.time.toFixed(1)}s`);
}

writeFileSync(
  new URL('../src/level-seeds.js', import.meta.url),
  `// Generated by scripts/find-seeds.mjs: one layout seed per level, each\n// checked to be finishable by the autopilot. Re-run the script after\n// changing the course generator, physics or bot.\nexport const LEVEL_SEEDS = ${JSON.stringify(seeds)};\n`
);
