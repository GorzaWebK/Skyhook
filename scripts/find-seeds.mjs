// Picks a random-layout seed for each level that the autopilot can finish
// without falling, and writes them (plus the autopilot's time, used for
// medals) to src/level-seeds.js.
//   node scripts/find-seeds.mjs
import { writeFileSync } from 'node:fs';
import { generateLevel } from '../src/course.js';
import { botRun } from '../src/botrun.js';
import { LEVEL_SEEDS as CURRENT } from '../src/level-seeds.js';

const LEVEL_COUNT = 30;

const seeds = [];
const pars = [];
for (let i = 0; i < LEVEL_COUNT; i++) {
  let found = null;
  // Keep the level's current layout if it still works, so players' best
  // times stay meaningful; otherwise search for a new one.
  const candidates = [CURRENT[i], ...Array.from({ length: 400 }, (_, k) => 1000 * (i + 1) + k)].filter((x) => x != null);
  for (let k = 0; k < candidates.length && !found; k++) {
    const seed = candidates[k];
    const course = generateLevel(i, seed, LEVEL_COUNT);
    const r = botRun(course);
    if (r.finished && r.falls === 0 && r.checkpoints.join() === course.checkpoints.map((c) => c.index).join()) {
      found = { seed, time: r.time, tries: k + 1, anchors: course.anchors.length, blockers: course.boxes.filter((b) => b.kind === 'blocker').length };
    }
  }
  if (!found) throw new Error(`no finishable seed for level ${i + 1}`);
  seeds.push(found.seed);
  pars.push(Math.round(found.time * 1000) / 1000);
  console.log(`level ${String(i + 1).padStart(2)}: seed ${found.seed} (try ${found.tries}), ${found.anchors} anchors, ${found.blockers} blockers, bot ${found.time.toFixed(1)}s`);
}

writeFileSync(
  new URL('../src/level-seeds.js', import.meta.url),
  `// Generated by scripts/find-seeds.mjs: one layout seed per level, each\n// checked to be finishable by the autopilot. Re-run the script after\n// changing the course generator, physics or bot.\nexport const LEVEL_SEEDS = ${JSON.stringify(seeds)};\n\n// The autopilot's finish time on each level (seconds). Gold medal time.\nexport const LEVEL_PAR = ${JSON.stringify(pars)};\n`
);
