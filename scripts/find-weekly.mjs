// Picks a storm layout for every weekly tournament (two years from the
// start week) that the autopilot can finish, and writes src/weekly-seeds.js.
//   node scripts/find-weekly.mjs
import { writeFileSync } from 'node:fs';
import { generateStormLevel } from '../src/course.js';
import { botRun } from '../src/botrun.js';

export const WEEKLY_START = '2026-11-16'; // a Monday
const WEEKS = 104;

const weeks = [];
for (let w = 0; w < WEEKS; w++) {
  const n = 2 + ((w * 3) % 8); // storm difficulty 2..9 (like levels 33-40)
  let found = null;
  for (let k = 0; k < 300 && !found; k++) {
    const seed = 800000 + w * 300 + k;
    const course = generateStormLevel(n, seed);
    const r = botRun(course);
    if (r.finished && r.falls === 0 && r.checkpoints.join() === course.checkpoints.map((c) => c.index).join()) {
      found = [n, seed, Math.round(r.time * 1000) / 1000];
    }
  }
  if (!found) throw new Error(`no finishable layout for week ${w}`);
  weeks.push(found);
}
writeFileSync(
  new URL('../src/weekly-seeds.js', import.meta.url),
  `// Generated by scripts/find-weekly.mjs: one storm layout per week from\n` +
  `// WEEKLY_START (a Monday), each checked finishable by the autopilot.\n` +
  `// [storm difficulty 0-9, seed, autopilot time].\n` +
  `export const WEEKLY_START = '${WEEKLY_START}';\n` +
  `export const WEEKLY = ${JSON.stringify(weeks)};\n`
);
console.log(`wrote ${weeks.length} weeks`);
