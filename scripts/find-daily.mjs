// Picks a layout for every daily challenge (two years from the start date)
// that the autopilot can finish, and writes them to src/daily-seeds.js.
//   node scripts/find-daily.mjs
import { writeFileSync } from 'node:fs';
import { generateLevel } from '../src/course.js';
import { botRun } from '../src/botrun.js';

export const DAILY_START = '2026-11-19';
const DAYS = 730;

// Difficulty (as a level index) wanders between level 9 and level 23.
export function dailyDifficulty(day) {
  return 8 + ((day * 7) % 15);
}

const days = [];
for (let day = 0; day < DAYS; day++) {
  const index = dailyDifficulty(day);
  let found = null;
  for (let k = 0; k < 200 && !found; k++) {
    const seed = 500000 + day * 200 + k;
    const course = generateLevel(index, seed, 30);
    const r = botRun(course);
    if (r.finished && r.falls === 0 && r.checkpoints.join() === course.checkpoints.map((c) => c.index).join()) {
      found = [index, seed, Math.round(r.time * 1000) / 1000];
    }
  }
  if (!found) throw new Error(`no finishable layout for day ${day}`);
  days.push(found);
  if (day % 100 === 0) console.log(`day ${day}: level ${found[0] + 1} difficulty, seed ${found[1]}, bot ${found[2]}s`);
}

writeFileSync(
  new URL('../src/daily-seeds.js', import.meta.url),
  `// Generated by scripts/find-daily.mjs: one layout per day from DAILY_START,\n` +
  `// each checked to be finishable by the autopilot. [difficulty index, seed,\n` +
  `// autopilot time]. Re-run after changing the generator, physics or bot.\n` +
  `export const DAILY_START = '${DAILY_START}';\n` +
  `export const DAILY = ${JSON.stringify(days)};\n`
);
console.log(`wrote ${days.length} days`);
